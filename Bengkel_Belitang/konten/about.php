<h3>About US</h3>
Aplikasi Data Onderdil 
Bengkel Sidorahayu ini merupakan aplikasi berbasis web yang mendukung kualitas pelayanan dan memudahkan 
kegiatan pemasukan maupun pengeluaran barang yang ada di Bengkel Sidorahayu. 
Aplikasi ini juga salah satu terobosan terbaru bagi bengkel - bengkel lainnya dalam mendata dan mengklasifikasikan
 onderdil - onderdil yang ada di dalam bengkel.<p>
Aplikasi ini dipergunakan untuk mengkalsifikasikan jenis onderdil
 sesuai dengan id ataupun nama onderdil itu sendiri. Aplikasi ini juga dapat memantau 
 ketersediaan stok barang onderdil dan juga harga onderdil tersebut.
 Dan dari aplikasi ini juga user dapat mendata kapan onderdil itu masuk atau telah
 terdaftar di bengkel tersebut serta dapat memberikan keterangan bahwa onderdil yang diinput
 dibelli secara lunas atau kontan maupun masih  dalam jangka waktu cicilan ataupun masihdalam keadaan hutang.
